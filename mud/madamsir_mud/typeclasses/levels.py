# Advancement level titles
LEVEL_TITLES = {
    (1, 5): "Novice",
    (6, 10): "Apprentice",
    (11, 20): "Journeyman",
    (21, 30): "Expert",
    (31, 40): "Master",
    (41, 50): "Grandmaster",
    (51, 75): "Legend",
    (76, 100): "Immortal",
    (101, 200): "Eternal",
}

def get_level_title(level):
    """Return title for a given level."""
    for (low, high), title in LEVEL_TITLES.items():
        if low <= level <= high:
            return title
    return "Unknown"

def get_xp_for_level(level):
    """Return XP needed for next level."""
    if level in LEVEL_TABLE:
        return LEVEL_TABLE[level]
    # Compute using formula for levels beyond 200
    return level_cost(level)

def get_total_xp_to_level(target_level):
    """Return cumulative XP needed to reach target level."""
    total = 0
    for lv in range(1, target_level + 1):
        total += get_xp_for_level(lv)
    return total

def get_level_progress(current_xp, current_level):
    """Return progress percentage to next level."""
    if current_level >= 200:
        return 100.0
    needed = get_xp_for_level(current_level + 1)
    prev_total = get_total_xp_to_level(current_level)
    current_in_level = current_xp - prev_total
    return min(100.0, (current_in_level / needed) * 100)
