import math

# Level formula from Islands of Myth
def level_cost(level):
    """Calculate XP cost for a single level."""
    return int(51500 * (1.122 ** (level / 2)))

def cumulative_cost(target_level):
    """Calculate total XP needed to reach target level from level 1."""
    total = 0
    for lv in range(1, target_level + 1):
        adv = level_cost(lv)
        guild = adv  # guild cost = advance cost
        total += adv + guild
    return total

